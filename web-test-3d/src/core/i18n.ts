const DICTS: Record<Lang, Dict> = { en, es, fr, de, it };

function detectInitialLang(): Lang {
  if (typeof window !== "undefined") {
    const q = new URLSearchParams(window.location.search).get("lang")?.slice(0, 2).toLowerCase();
    if (q && (LANGS as readonly string[]).includes(q)) return q as Lang;
    const nav = navigator.language?.slice(0, 2).toLowerCase();
    if (nav && (LANGS as readonly string[]).includes(nav)) return nav as Lang;
  }
  return "en";
}

let activeLang: Lang = detectInitialLang();
const listeners = new Set<(lang: Lang) => void>();

export const getLang = (): Lang => activeLang;
export const setLang = (lang: Lang): void => {
  if (!DICTS[lang]) return;
  activeLang = lang;
  for (const fn of listeners) fn(lang);
};
export const onLangChange = (fn: (lang: Lang) => void): () => void => {
  listeners.add(fn);
  return () => listeners.delete(fn);
};

export function t(key: I18nKey | string, params: Record<string, string | number> = {}): string {
  const dict = DICTS[activeLang] as Record<string, string>;
  const fallback = en as Record<string, string>;
  const raw = dict[key] ?? fallback[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_m, k) => String(params[k] ?? `{${k}}`));
}

export function fmt(n: number, digits = 1): string {
  return n.toLocaleString(ASR_LOCALE[activeLang], {
    maximumFractionDigits: digits,
    minimumFractionDigits: digits,
  });
}
